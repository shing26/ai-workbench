import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const AGENCY_ROOT = join(ROOT, '.reasonix', 'agency-agents');
const OUT_DIR = join(ROOT, 'src', 'data');
const OUT_FILE = join(OUT_DIR, 'agencyCatalog.ts');

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return {};
  const out = {};
  for (const line of match[1].split(/\r?\n/)) {
    const idx = line.indexOf(':');
    if (idx <= 0) continue;
    out[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return out;
}

function stripFrontmatter(raw) {
  return raw.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, '').trim();
}

function splitTools(value) {
  if (!value) return [];
  return value
    .split(',')
    .map((tool) => tool.trim())
    .filter(Boolean);
}

function buildInstructions(frontmatter, body) {
  const trimmed = body
    .replace(/^#\s.*$/m, '')
    .trim()
    .slice(0, 900)
    .trim();
  return [
    frontmatter.description ?? '',
    frontmatter.vibe ? `## Vibe\n${frontmatter.vibe}` : '',
    `## Instructions\n${trimmed}`,
  ]
    .filter(Boolean)
    .join('\n\n');
}

const divisionsJson = JSON.parse(readFileSync(join(AGENCY_ROOT, 'divisions.json'), 'utf8'));
const divisions = divisionsJson.divisions;
const entries = [];

for (const [dir, meta] of Object.entries(divisions)) {
  const folder = join(AGENCY_ROOT, dir);
  if (!existsSync(folder)) continue;
  for (const file of readdirSync(folder).filter((name) => name.endsWith('.md'))) {
    const raw = readFileSync(join(folder, file), 'utf8');
    const frontmatter = parseFrontmatter(raw);
    if (!frontmatter.name) continue;
    entries.push({
      division: meta.label,
      name: frontmatter.name,
      slug: file.slice(0, -3),
      description: frontmatter.description ?? '',
      emoji: frontmatter.emoji ?? '🤖',
      color: frontmatter.color ?? meta.color,
      developerInstructions: buildInstructions(frontmatter, stripFrontmatter(raw)),
      tools: splitTools(frontmatter.tools),
      sourceUrl: `https://github.com/msitarzewski/agency-agents/blob/main/${dir}/${file}`,
    });
  }
}

entries.sort((a, b) => a.division.localeCompare(b.division) || a.slug.localeCompare(b.slug));

const divisionsOut = Object.entries(divisions).map(([id, meta]) => ({
  id,
  label: meta.label,
  icon: meta.icon,
  color: meta.color,
}));

mkdirSync(OUT_DIR, { recursive: true });
const output = [
  '// Generated by scripts/import-agency-agents.mjs - do not edit by hand.',
  "import type { AgencyAgentInput } from '../lib/db';",
  '',
  `export const AGENCY_CATALOG: AgencyAgentInput[] = ${JSON.stringify(entries)};`,
  '',
  `export const AGENCY_DIVISIONS = ${JSON.stringify(divisionsOut)};`,
  '',
].join('\n');
writeFileSync(OUT_FILE, output, 'utf8');
console.log(`Wrote ${entries.length} agents to ${OUT_FILE}`);
